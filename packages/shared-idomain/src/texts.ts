export function idomainText(lang: string, key: string, params: Record<string, string | number> = {}): string {
  const table: Record<string, string> = lang.startsWith('en') ? en : fr;
  const raw = table[key] ?? (fr as Record<string, string>)[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, k: string) => String(params[k] ?? ''));
}

