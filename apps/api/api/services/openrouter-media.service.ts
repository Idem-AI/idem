/**
 * Image et vision par OpenRouter.
 *
 * Image : endpoint dédié `POST /images` (FLUX.2), qui rend les octets en base64.
 * Vision : le chat multimodal OpenAI, comme chez Z.ai.
 *
 * Pas de vidéo ni de voix ici, volontairement : au catalogue OpenRouter du
 * 2026-10-11, AUCUN modèle vidéo n'a de poids ouverts (Wan 3.0 compris) et aucun
 * modèle de synthèse vocale n'est proposé (ni Qwen3-TTS ni Chatterbox). Les
 * brancher via OpenRouter irait contre l'objectif d'auto-hébergement ; ces deux
 * capacités restent donc sur leurs fournisseurs actuels (cf. docs/OPENROUTER.md).
 */

import axios from 'axios';

import logger from '../config/logger';
import {
  OPENROUTER_BASE_URL,
  getOpenRouterApiKey,
  isAllowedOpenRouterModel,
  openRouterHeaders,
  openRouterRouting,
  resolveOpenRouterModel,
} from '../config/openrouter.config';
import { getProvider } from '../config/ai-providers.config';
import { LLMProvider } from '../config/ai.config';

const IMAGE_TIMEOUT_MS = 120_000;
const VISION_TIMEOUT_MS = 60_000;

/** Ratios acceptés par les modèles d'image d'OpenRouter. */
const ASPECT_RATIOS: [string, number][] = [
  ['21:9', 21 / 9], ['16:9', 16 / 9], ['3:2', 3 / 2], ['4:3', 4 / 3], ['5:4', 5 / 4], ['1:1', 1],
  ['4:5', 4 / 5], ['3:4', 3 / 4], ['2:3', 2 / 3], ['9:16', 9 / 16],
];

export function isOpenRouterConfigured(): boolean {
  return Boolean(getOpenRouterApiKey());
}

function headers(): Record<string, string> {
  const key = getOpenRouterApiKey();
  if (!key) throw new Error('OPENROUTER_API_KEY is not configured — OpenRouter media calls are unavailable');
  return { Authorization: `Bearer ${key}`, ...openRouterHeaders() };
}

/** « 1344x768 » → le ratio supporté le plus proche (« 16:9 »). */
export function aspectRatioFor(size?: string): string {
  const match = /^(\d+)x(\d+)$/.exec(size ?? '');
  if (!match) return '16:9';
  const ratio = Number(match[1]) / Number(match[2]);
  return ASPECT_RATIOS.reduce((best, current) =>
    Math.abs(current[1] - ratio) < Math.abs(best[1] - ratio) ? current : best
  )[0];
}

/**
 * Un nom de modèle venu d'un appelant est-il un identifiant OpenRouter ?
 * Les identifiants OpenRouter portent toujours un « éditeur/ » ; un nom GLM
 * (« glm-image ») ou Gemini ne doit jamais leur être envoyé.
 */
const isOpenRouterId = (model?: string): model is string => Boolean(model && model.includes('/'));

export interface OpenRouterImage {
  buffer: Buffer;
  mimeType: string;
  model: string;
}

export async function generateImageWithOpenRouter(
  prompt: string,
  options: { size?: string; model?: string; fallbackModel?: string; tag?: string } = {}
): Promise<OpenRouterImage> {
  const requested = isOpenRouterId(options.model) ? options.model : undefined;
  const model =
    requested && isAllowedOpenRouterModel(requested)
      ? requested
      : resolveOpenRouterModel('image', (message) => logger.warn(`[OPENROUTER] ${message}`));
  const envFallback = process.env.IDEM_OPENROUTER_IMAGE_FALLBACK_MODEL?.trim();
  const fallback = [options.fallbackModel, envFallback].find(
    (candidate): candidate is string =>
      isOpenRouterId(candidate) && candidate !== model && isAllowedOpenRouterModel(candidate)
  );

  const attempt = async (candidate: string): Promise<OpenRouterImage> => {
    const started = Date.now();
    const response = await axios.post<{ data?: { b64_json?: string; media_type?: string }[] }>(
      `${OPENROUTER_BASE_URL()}/images`,
      {
        model: candidate,
        prompt,
        n: 1,
        aspect_ratio: aspectRatioFor(options.size),
        output_format: 'png',
        ...openRouterRouting(),
      },
      { headers: headers(), timeout: IMAGE_TIMEOUT_MS }
    );

    const entry = response.data?.data?.[0];
    if (!entry?.b64_json) throw new Error(`${candidate} n'a renvoyé aucune image`);

    const buffer = Buffer.from(entry.b64_json, 'base64');
    logger.info(`[OPENROUTER] image generated by ${candidate}`, {
      tag: options.tag,
      durationMs: Date.now() - started,
      bytes: buffer.length,
    });
    return { buffer, mimeType: entry.media_type || 'image/png', model: candidate };
  };

  try {
    return await attempt(model);
  } catch (error: any) {
    if (!fallback) throw error;
    logger.warn(`[OPENROUTER] ${model} failed (${error?.message}) — falling back to ${fallback}`);
    return attempt(fallback);
  }
}

export async function analyzeImageWithOpenRouter(
  base64: string,
  mimeType: string,
  instruction: string,
  options: { model?: string; fallbackModel?: string; maxOutputTokens?: number; temperature?: number } = {}
): Promise<string> {
  const requested = isOpenRouterId(options.model) ? options.model : undefined;
  const model =
    requested && isAllowedOpenRouterModel(requested)
      ? requested
      : resolveOpenRouterModel('vision', (message) => logger.warn(`[OPENROUTER] ${message}`));
  // Repli : le modèle de lecture de texte du fournisseur (autre famille de poids).
  const fallback = getProvider(LLMProvider.OPENROUTER).models?.ocr;

  const attempt = async (candidate: string): Promise<string> => {
    const response = await axios.post<{ choices?: { message?: { content?: string } }[] }>(
      `${OPENROUTER_BASE_URL()}/chat/completions`,
      {
        model: candidate,
        messages: [
          {
            role: 'user',
            content: [
              { type: 'image_url', image_url: { url: `data:${mimeType};base64,${base64}` } },
              { type: 'text', text: instruction },
            ],
          },
        ],
        max_tokens: options.maxOutputTokens ?? 1500,
        temperature: options.temperature ?? 0.1,
        // Le raisonnement se décompte du budget de sortie : sur le petit JSON
        // attendu il le viderait (cf. `translateReasoning`).
        reasoning: { enabled: false },
        ...openRouterRouting(),
      },
      { headers: headers(), timeout: VISION_TIMEOUT_MS }
    );
    return response.data?.choices?.[0]?.message?.content?.trim() ?? '';
  };

  try {
    return await attempt(model);
  } catch (error: any) {
    if (!fallback || fallback === model) throw error;
    logger.warn(`[OPENROUTER] vision failed on ${model} (${error?.message}) — trying ${fallback}`);
    return attempt(fallback);
  }
}
